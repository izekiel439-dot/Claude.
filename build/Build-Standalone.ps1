<#
.SYNOPSIS
    Bundles Invoke-PCScan.ps1 and the lib folder into one self-contained .ps1.

.DESCRIPTION
    The multi-file layout is easier to read and maintain, but a single file is
    far easier to get onto a machine - save it, right-click, run. This script
    inlines each lib file in dot-source order, replacing the loader block.

    Run it after changing anything under lib/ and commit the result.

.EXAMPLE
    .\build\Build-Standalone.ps1
#>

[CmdletBinding()]
param(
    [string]$OutputPath
)

$ErrorActionPreference = 'Stop'

$repoRoot = Split-Path $PSScriptRoot -Parent
$entry    = Join-Path $repoRoot 'Invoke-PCScan.ps1'
if (-not $OutputPath) { $OutputPath = Join-Path $repoRoot 'ArgusScan-Standalone.ps1' }

# Must match the dot-source order in Invoke-PCScan.ps1.
$modules = @(
    'Core.ps1'
    'Checks.Persistence.ps1'
    'Checks.Defender.ps1'
    'Checks.Network.ps1'
    'Checks.Accounts.ps1'
    'Report.ps1'
)

$source = Get-Content -LiteralPath $entry -Raw

# The loader block runs from $PSScriptRoot\lib; the bundle has no lib folder.
$loaderPattern = '(?ms)^\$libraryPath = Join-Path \$PSScriptRoot ''lib''.*?^\}\r?\n'
if ($source -notmatch $loaderPattern) {
    throw "Could not locate the module loader block in $entry. Update the pattern in this build script."
}

$bundle = New-Object System.Text.StringBuilder
$null = $bundle.AppendLine('#region ---- Embedded modules (generated by build/Build-Standalone.ps1 - do not edit here) ----')
$null = $bundle.AppendLine()

foreach ($module in $modules) {
    $path = Join-Path (Join-Path $repoRoot 'lib') $module
    if (-not (Test-Path -LiteralPath $path)) { throw "Missing module: $path" }

    $null = $bundle.AppendLine("# ============================ lib/$module ============================")
    $null = $bundle.AppendLine((Get-Content -LiteralPath $path -Raw).TrimEnd())
    $null = $bundle.AppendLine()
}

$null = $bundle.AppendLine('#endregion ---- Embedded modules ----')

$result = [regex]::Replace($source, $loaderPattern, { $bundle.ToString() })

$banner = @"
# ---------------------------------------------------------------------------
# GENERATED FILE - built from Invoke-PCScan.ps1 + lib/ by build/Build-Standalone.ps1
# Edit the sources in the repository, not this file, then rebuild.
# ---------------------------------------------------------------------------

"@

Set-Content -LiteralPath $OutputPath -Value ($banner + $result) -Encoding UTF8

$sizeKb = [math]::Round((Get-Item -LiteralPath $OutputPath).Length / 1KB, 1)
Write-Host "Built $OutputPath ($sizeKb KB, $($modules.Count) modules inlined)" -ForegroundColor Green
